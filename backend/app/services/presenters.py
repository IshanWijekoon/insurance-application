"""Assembles database rows into API read models.

This is the single place where economic values cross into responses, so it is the single
place that enforces the rule: a value is either `AVAILABLE` with a currency and sources, or
`UNAVAILABLE` with a reason and a manual-verification flag. Nothing downstream can render
a fabricated number because nothing downstream ever receives a bare figure.
"""

